'use strict';

/**
 * Plooplayer routes — answered here, ahead of the SDK router, because the
 * stream handler needs the request's public origin (for the /configure link)
 * and the catalogs exist only for installs that configured a list.
 *
 *   GET /:config/catalog/Plooplayer/:id[/:extra].json
 *   GET /:config/meta/Plooplayer/:id.json
 *   GET /:config/stream/Plooplayer/:id.json
 *   GET /plooplayer/decryptor.js      the local decryptor as one script (Termux / PC)
 *
 * Everything here is text. Media never transits the add-on (I1): ClearKey
 * channels point at the viewer's local decryptor. Any other type/id falls
 * through to the regular handlers.
 */

const path = require('path');
const express = require('express');
const { decodeConfigSegment } = require('../configSegment');
const { getRequestBaseUrl } = require('../config');
const { parseExtraSegment } = require('./replaySubcatalogs');
const { isPlooplayerRequest } = require('../services/PlooplayerService');

const SRC_ROOT = path.join(__dirname, '..');
const DECRYPTOR_ENTRY = path.join(SRC_ROOT, 'services', 'plooplayer', 'localDecryptorCli.js');

function rawExtraSegment(req) {
  const p = typeof req.path === 'string' ? req.path : '';
  const last = p.slice(p.lastIndexOf('/') + 1);
  return last.endsWith('.json') ? last.slice(0, -5) : (req.params.extra || '');
}

function sendJson(res, result, fallbackMaxAge) {
  const maxAge = Number.isInteger(result && result.cacheMaxAge) ? result.cacheMaxAge : fallbackMaxAge;
  const swr = Number.isInteger(result && result.staleRevalidate) ? result.staleRevalidate : maxAge * 2;
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Content-Type', 'application/json; charset=utf-8');
  res.setHeader('Cache-Control', `max-age=${maxAge}, stale-while-revalidate=${swr}, public`);
  const body = { ...result };
  delete body.cacheMaxAge;
  delete body.staleRevalidate;
  return res.status(200).send(JSON.stringify(body));
}

/** Builds the decryptor script once per process; null when this build lacks the sources (ncc dist). */
function createDecryptorScriptLoader() {
  let cached;
  return function loadDecryptorScript() {
    if (cached !== undefined) return cached;
    try {
      const { bundleCommonJs } = require('../services/plooplayer/scriptBundler');
      const { VERSION } = require('../services/plooplayer/localDecryptor');
      cached = bundleCommonJs(DECRYPTOR_ENTRY, {
        rootDir: SRC_ROOT,
        stubs: [path.join(SRC_ROOT, 'services', 'ProviderOutbound.js')],
        allowExternal: ['fast-xml-parser'],
        banner: [
          `Plooplayer local decryptor v${VERSION} — generated by the add-on, do not edit.`,
          'Run: node ploo-decryptor.js   (PORT=8090, HOST=127.0.0.1 by default; HOST=0.0.0.0 for the LAN)'
        ]
      }).code;
    } catch (err) {
      console.error(`[Plooplayer] decryptor bundle unavailable: ${err && err.message}`);
      cached = null;
    }
    return cached;
  };
}

/**
 * @param {{ getService: () => import('../services/PlooplayerService') }} deps
 */
function createPlooplayerRouter({ getService }) {
  const router = express.Router();
  const loadDecryptorScript = createDecryptorScriptLoader();
  const configOf = (req) => decodeConfigSegment(req.params.config) || {};

  const guarded = (what, fallback, handler) => async (req, res, next) => {
    if (!isPlooplayerRequest(req.params.type, req.params.id)) return next();
    try {
      return await handler(req, res);
    } catch (err) {
      console.error(`[Plooplayer] ${what} ${req.params.id} failed: ${err && err.message}`);
      if (res.headersSent) return undefined;
      return sendJson(res, fallback, 30);
    }
  };

  router.get(['/:config/catalog/:type/:id.json', '/:config/catalog/:type/:id/:extra.json'],
    guarded('catalog', { metas: [] }, async (req, res) => {
      const extra = req.params.extra ? parseExtraSegment(rawExtraSegment(req)) : {};
      const result = await getService().catalog({ id: req.params.id, extra, config: configOf(req) });
      return sendJson(res, result, 600);
    }));

  router.get('/:config/meta/:type/:id.json',
    guarded('meta', { meta: null }, async (req, res) => {
      const result = await getService().meta({ id: req.params.id, config: configOf(req) });
      return sendJson(res, result, 600);
    }));

  router.get('/:config/stream/:type/:id.json',
    guarded('stream', { streams: [] }, async (req, res) => {
      const result = await getService().streams({
        id: req.params.id,
        config: configOf(req),
        baseUrl: getRequestBaseUrl(req)
      });
      return sendJson(res, result, 60);
    }));

  router.get('/plooplayer/decryptor.js', (req, res) => {
    const script = loadDecryptorScript();
    if (!script) return res.status(503).type('text/plain').send('Decryptor script is not available in this build');
    res.setHeader('Content-Type', 'application/javascript; charset=utf-8');
    res.setHeader('Content-Disposition', 'inline; filename="ploo-decryptor.js"');
    res.setHeader('Cache-Control', 'public, max-age=3600');
    return res.status(200).send(script);
  });

  return router;
}

module.exports = { createPlooplayerRouter };
